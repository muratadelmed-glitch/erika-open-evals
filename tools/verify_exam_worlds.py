"""Check that the public world generator reproduces the hard worlds used by IP1 and by data/hard-dev.

Usage (repository root):  python3 tools/verify_exam_worlds.py

For each world it regenerates the world with world/dunya.py and the hard setting
DunyaAyar(birey=30, iz_piksel=1, iz_sapma=0.04, koku=True, koku_aile=0.5), then compares with the published files:
  - the encounter order (answers_<seed>.npz: stream_object),
  - the colour of every tested object (cue_object -> cue_colour),
  - the palette (world_<seed>.npz: palette).
This shows that the locked exam used exactly the worlds it names, generated by public code.
"""
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from world.dunya import Dunya, DunyaAyar  # noqa: E402

HARD = DunyaAyar(birey=30, iz_piksel=1, iz_sapma=0.04, koku=True, koku_aile=0.5)
SETS = (("records/2026-11-IP1/data", range(312021, 312041)), ("data/hard-dev", range(310800, 310820)))


def main():
    bad, n = [], 0
    for base, seeds in SETS:
        for w in seeds:
            n += 1
            d = Dunya(w, HARD)
            ans = np.load(ROOT / base / f"answers_{w}.npz")
            ok = (np.array_equal(np.asarray(d.akis[:d.ayar.karsilasma]), ans["stream_object"])
                  and all(d.birey(int(o)).renk == int(c) for o, c in zip(ans["cue_object"], ans["cue_colour"]))
                  and np.allclose(np.asarray(d.palet, np.float32), np.load(ROOT / base / f"world_{w}.npz")["palette"]))
            if not ok:
                bad.append(w)
    print(f"{n} hard worlds regenerated: " + ("all match the published files" if not bad else f"MISMATCH {bad}"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
